import Foundation

/// Renders a module's public API surface from its Swift symbol graph (`swift package dump-symbol-graph`), as a
/// sorted, stable Markdown list the Kotlin port diffs against (ADR-0002 Key Interfaces, Validation 4).
enum APISurface {
    struct Failure: Error, CustomStringConvertible { let description: String }

    static func render(symbolGraphDir: String, module: String) throws -> String {
        let fm = FileManager.default
        let files = try fm.contentsOfDirectory(atPath: symbolGraphDir)
            .filter { $0.hasPrefix(module + ".") && $0.hasSuffix(".symbols.json") }.sorted()
        guard !files.isEmpty else { throw Failure(description: "no symbol graph for \(module) in \(symbolGraphDir)") }
        var lines = Set<String>()
        for f in files {
            let data = try Data(contentsOf: URL(fileURLWithPath: symbolGraphDir).appendingPathComponent(f))
            guard let root = try JSONSerialization.jsonObject(with: data) as? [String: Any],
                  let symbols = root["symbols"] as? [[String: Any]] else { continue }
            for s in symbols {
                guard (s["accessLevel"] as? String) == "public",
                      let kind = (s["kind"] as? [String: Any])?["identifier"] as? String,
                      let path = s["pathComponents"] as? [String],
                      let frags = (s["declarationFragments"] as? [[String: Any]]) else { continue }
                let decl = frags.compactMap { $0["spelling"] as? String }.joined()
                    .split(whereSeparator: { $0 == "\n" }).map { $0.trimmingCharacters(in: .whitespaces) }.joined(separator: " ")
                lines.insert("- `\(path.joined(separator: "."))` (\(kind.replacingOccurrences(of: "swift.", with: ""))): `\(decl)`")
            }
        }
        let header = "# \(module) public API surface\n\nGenerated by `kidtools api-surface` from the Swift symbol graph; do not edit by hand.\nThe Kotlin port diffs its names and shapes against this file (ADR-0002).\n\n"
        return header + lines.sorted().joined(separator: "\n") + "\n"
    }
}
